import { createPublicKey } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { calculateReportHash, signStage6Approval } from "./stage6-approval-crypto.mjs";

const root = resolve(import.meta.dirname, "..");
const option = (name) => { const index = process.argv.indexOf(name); return index >= 0 ? process.argv[index + 1] : undefined; };
const reportPath = option("--report");
const approvalType = option("--type");
const role = option("--role");
const approverId = option("--approver-id");
const keyId = option("--key-id");
const privateKeyPath = option("--private-key");
if (!reportPath || !["pilot", "final"].includes(approvalType) || !role || !approverId || !keyId || !privateKeyPath) throw new Error("report, type, role, approver, key, and external private key are required");
const keyring = JSON.parse(await readFile(resolve(root, "contracts/release/stage6-approver-keyring.json"), "utf8"));
const key = keyring.keys.find((item) => item.keyId === keyId && item.approverId === approverId && item.status === "active" && item.roles?.includes(role));
if (keyring.status !== "active" || !key || !keyring.requiredRoles[approvalType]?.includes(role)) throw new Error("approver is not active for the requested Stage 6 role");
const privateKeyPem = await readFile(resolve(privateKeyPath), "utf8");
const publicFromPrivate = createPublicKey(privateKeyPem).export({ type: "spki", format: "pem" });
if (publicFromPrivate.trim() !== key.publicKeyPem.trim()) throw new Error("private key does not match the source-bound public key");
const target = resolve(root, reportPath);
const report = JSON.parse(await readFile(target, "utf8"));
if (report.signatures?.some((item) => item.role === role || item.approverId === approverId || item.keyId === keyId)) throw new Error("role, approver, or key already signed this report");
const signature = signStage6Approval(report, { approvalType, role, approverId, keyId, privateKeyPem });
const signatures = [...(report.signatures ?? []), signature].sort((left, right) => keyring.requiredRoles[approvalType].indexOf(left.role) - keyring.requiredRoles[approvalType].indexOf(right.role));
const updated = { ...report, signatures };
updated.reportHash = calculateReportHash(updated);
await writeFile(target, `${JSON.stringify(updated, null, 2)}\n`);
console.log(`signed Stage 6 ${approvalType} approval: role=${role} approver=${approverId} key=${keyId}`);
