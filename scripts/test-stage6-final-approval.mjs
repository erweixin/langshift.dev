import assert from "node:assert/strict";
import { readFile } from "node:fs/promises";
import { resolve } from "node:path";
import { calculateApprovalScopeHash, calculateReportHash } from "./stage6-approval-crypto.mjs";
import { requiredFinalEvidencePaths } from "./stage6-evidence-manifest.mjs";
import { buildFinalApprovalReport } from "./write-stage6-final-approval.mjs";

const root = resolve(import.meta.dirname, "..");
const layout = JSON.parse(await readFile(resolve(root, "contracts/release/stage6-evidence-layout.json"), "utf8"));
const sourceCommit = "a".repeat(40);
const rcHash = "b".repeat(64);
const paths = requiredFinalEvidencePaths(layout);
const artifacts = paths.map((path, index) => ({ path, sha256: (index % 16).toString(16).repeat(64), sizeBytes: index + 1 }));
const reportKeys = ["stage1", "stage2", "stage3", "stage4", "stage5", "penetration", "profile_route_planner", "profile_daily_planner", "profile_coach", "profile_evaluator", "profile_artifact_builder", "capacity", "recovery", "deployment_compose", "deployment_helm_tofu", "deployment_official_cloud", "pilot", "pilot_equivalence"];
const summaries = reportKeys.map((key) => ({ key, path: `${layout.root}/${layout.reports[key]}`, status: key === "pilot" ? "approved" : "passed", reportHash: "c".repeat(64), statusValid: true, reportHashValid: true, signaturePresent: true, bindingValid: true }));
const options = { generatedAt: "2026-01-31T00:00:00.000Z", worktreeDirty: false, layout };
const build = (changes = {}, optionChanges = {}) => buildFinalApprovalReport({ sourceCommit, rcHash, artifacts, reportSummaries: summaries, legalActive: true, ...changes }, { ...options, ...optionChanges });
const report = build();
assert.equal(report.status, "approved");
assert.equal(report.evidenceCount, paths.length);
assert.equal(report.verifiedReports.length, reportKeys.length);
assert.equal(report.approvalScopeHash, calculateApprovalScopeHash(report));
assert.equal(report.reportHash, calculateReportHash(report));
assert.match(report.evidenceManifestHash, /^[0-9a-f]{64}$/);
assert.equal(build({}, { worktreeDirty: true }).status, "failed");
assert.throws(() => build({ artifacts: artifacts.slice(1) }), /incomplete/);
const tampered = structuredClone(artifacts); tampered[0].sha256 = "not-a-hash";
assert.throws(() => build({ artifacts: tampered }), /incomplete/);
const unsigned = structuredClone(summaries); unsigned[0].signaturePresent = false;
assert.throws(() => build({ reportSummaries: unsigned }), /unsigned/);
const unbound = structuredClone(summaries); unbound.at(-1).bindingValid = false;
assert.throws(() => build({ reportSummaries: unbound }), /not source\/RC bound/);
assert.throws(() => build({ legalActive: false }), /invalid/);
console.log(`Stage 6 final approval self-test passed: ${paths.length} exact artifacts and ${reportKeys.length} signed reports accepted; missing/tampered/unsigned/unbound/legal/dirty mutations rejected`);
